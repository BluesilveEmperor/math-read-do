#!/usr/bin/env bash
# Build a nature-* beamer deck.
#
#   bash build/build.sh slate                 # XeLaTeX, two passes
#   bash build/build.sh all                   # every demo theme
#   bash build/build.sh slate --bib           # latexmk + biber
#   bash build/build.sh path/to/deck.tex      # an arbitrary deck
#
# Why this script exists rather than a bare xelatex call:
#   * The theme needs an ABSOLUTE figure root (see beamer-nature-common.sty).
#     Relative paths with "../" are rejected by kpathsea as soon as an output
#     directory is in play, so the root is computed here and injected.
#   * Two XeLaTeX passes are required for the frame total in the footer.
#   * latexmk + biber needs the same absolute root, so both paths share it.

set -u

# Git Bash resolves binaries only through POSIX-style paths ("/d/texlive/..."),
# not through the Windows "D:/..." form, so the POSIX spelling is used here.
TEXBIN="${TEXBIN:-/d/texlive/2026/bin/windows}"
case ":$PATH:" in
  *":$TEXBIN:"*) ;;
  *) PATH="$TEXBIN:$PATH" ;;
esac
export PATH

# A TeX binary that does not exist is the single most likely setup failure, so
# fail loudly instead of producing a confusing "blank PDF" result.
if ! command -v xelatex >/dev/null 2>&1; then
  echo "ERROR: xelatex not found. Set TEXBIN to your TeX Live bin directory" >&2
  echo "       (tried: $TEXBIN)" >&2
  exit 127
fi

PYTHON="${PYTHON:-}"
if [ -z "$PYTHON" ]; then
  # Prefer the managed interpreter (it has PyMuPDF), then fall back to whatever
  # is on PATH. Test executability directly: "command -v" does not resolve a
  # fully-qualified POSIX path the way this script needs.
  for cand in \
    "/c/Users/HW/.workbuddy/binaries/python/versions/3.13.12/python" \
    "python3" "python"; do
    if [ -x "$cand" ] || command -v "$cand" >/dev/null 2>&1; then
      PYTHON="$cand"; break
    fi
  done
fi
[ -z "$PYTHON" ] && PYTHON="python"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BEAMER_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
BUILD_DIR="$SCRIPT_DIR"
PREVIEW_DIR="$BUILD_DIR/preview"

# Absolute root the deck resolves figures against. Overridable for external decks.
NT_ROOT="${NT_ROOT:-$BEAMER_DIR}"

THEME="${1:-slate}"
USE_BIB=0
for arg in "$@"; do
  [ "$arg" = "--bib" ] && USE_BIB=1
done

# One shared demo source renders every theme, so the theme name is injected
# alongside the figure root. A caller-supplied .tex keeps its own theme choice.
resolve_tex() {
  case "$1" in
    all) echo "$BEAMER_DIR/demo/demo.tex" ;;
    *.tex) echo "$1" ;;
    *) echo "$BEAMER_DIR/demo/demo.tex" ;;
  esac
}

build_one() {
  local tex="$1"
  local theme="$2"
  # TeX always names output after the source file, so the produced PDF is
  # <source stem>.pdf; a per-theme alias is created afterwards.
  local srcterm
  srcterm="$(basename "$tex" .tex)"
  local out="$BUILD_DIR/${srcterm}-${theme}.pdf"
  local pretex="\def\ntFiguresRoot{$NT_ROOT}\def\ntThemeName{$theme}"

  # Parameters are passed through a generated file rather than -usepretex,
  # because XeLaTeX applies -usepretex after the preamble and it therefore
  # cannot override anything the document defines for itself.
  # The file is written next to the *output* as well as the source, since
  # \InputIfFileExists resolves a relative name against the output directory
  # when one is in use; the absolute path is injected too as a belt-and-braces
  # measure for decks that pass their own settings file.
  # A trailing double backslash in a DOS path would escape the following
  # character, so backslashes are normalised to forward slashes here.
  local root_posix="${NT_ROOT//\\//}"
  local settings="$BUILD_DIR/ntsettings.tex"
  printf '%% Generated by build.sh -- do not edit; regenerated on every build.\n\\def\\ntThemeName{%s}\n\\def\\ntFiguresRoot{%s}\n' \
    "$theme" "$root_posix" > "$settings"
  cp "$settings" "$BEAMER_DIR/demo/ntsettings.tex"

  echo ">>> $srcterm   theme=$theme  root=$NT_ROOT"

  if [ "$USE_BIB" = "1" ]; then
    latexmk -xelatex -bibtex- -interaction=nonstopmode \
      -jobname="$srcterm-$theme" -outdir="$BUILD_DIR" "$tex" \
      > "$BUILD_DIR/log-$srcterm-$theme.latexmk.txt" 2>&1
    rc=$?
    logf="$BUILD_DIR/log-$srcterm-$theme.latexmk.txt"
  else
    local i rc=0
    for i in 1 2 3; do
      xelatex -interaction=nonstopmode -jobname="$srcterm-$theme" \
        -output-directory="$BUILD_DIR" "$tex" \
        > "$BUILD_DIR/log-$srcterm-$theme.txt" 2>&1
      rc=$?
      if [ $i -ge 2 ] && ! grep -q "Rerun" "$BUILD_DIR/log-$srcterm-$theme.txt" 2>/dev/null; then
        break
      fi
    done
    logf="$BUILD_DIR/log-$srcterm-$theme.txt"
  fi

  if [ -f "$out" ]; then
    local errs stats
    errs="$(grep -cE '^!|Unable to load|LaTeX Error' "$logf" 2>/dev/null || true)"
    [ -z "$errs" ] && errs=0
    stats="$("$PYTHON" "$BUILD_DIR/pdf_tools.py" "$out" "" "$srcterm-$theme" 2>/dev/null)"
    [ -z "$stats" ] && stats="pages=? ratio=?"
    echo "    OK  exit=$rc  errors=$errs  $stats  -> $out"
    return 0
  else
    echo "    FAIL exit=$rc  (see $logf)"
    grep -nE '^!|Unable to load|LaTeX Error' "$logf" 2>/dev/null | head -5
    return 1
  fi
}

render_preview() {
  local pdf="$1" stem="$2"
  mkdir -p "$PREVIEW_DIR"
  "$PYTHON" "$BUILD_DIR/pdf_tools.py" "$pdf" "$PREVIEW_DIR" "$stem" 150 2>/dev/null \
    | sed 's/^/    preview: /' || echo "    (preview skipped)"
}

rc_all=0
if [ "$THEME" = "all" ]; then
  for t in slate navy ink paper; do
    tex="$BEAMER_DIR/demo/demo.tex"
    if build_one "$tex" "$t" "all"; then
      render_preview "$BUILD_DIR/demo-$t.pdf" "demo-$t"
    else
      rc_all=1
    fi
  done
else
  tex="$(resolve_tex "$THEME")"
  if build_one "$tex" "$THEME" "one"; then
    render_preview "$BUILD_DIR/$(basename "$tex" .tex)-$THEME.pdf" \
                   "$(basename "$tex" .tex)-$THEME"
  else
    rc_all=1
  fi
fi

# The figure slide is the only layout where content and page furniture compete
# for the same space, and a panel overlapping the footer is invisible at a
# glance. Re-measure it on the PDFs rather than trusting the render.
if [ "$THEME" = "all" ]; then
  echo ""
  echo ">>> clearance check (takeaway panel vs footer)"
  "$PYTHON" "$BUILD_DIR/check_clearance.py" "$BEAMER_DIR" 2>&1 | sed 's/^/    /'
  [ "${PIPESTATUS[0]}" -ne 0 ] && rc_all=1
fi

exit $rc_all
